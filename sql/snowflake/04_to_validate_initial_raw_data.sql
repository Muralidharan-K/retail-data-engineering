from retail_db.information_schema.tables
where table_schema = 'RAW'
and table_name in (
    'CUSTOMERS',
    'ORDERS',
    'ORDER_ITEMS',
    'PAYMENTS',
    'PRODUCTS',
    'STORES'
);

